@contextmanager
def db():
    if DATABASE_URL:
        connection = _postgres_connect()
        try:
            yield PostgresConnection(connection)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()
    else:
        connection = sqlite3.connect(DB_PATH, timeout=20)
        connection.row_factory = sqlite3.Row
        connection.execute('PRAGMA foreign_keys=ON')
        try:
            yield connection
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()


def audit(actor, action, detail='', ip=''):
    with db() as connection:
        connection.execute(
            'INSERT INTO audit_logs(actor_id,action,detail,ip) VALUES(?,?,?,?)',
            (actor, action, detail, ip)
        )
